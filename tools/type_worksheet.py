#!/usr/bin/env python3
"""Build the typing worksheet for the globals that block the transliterated bodies.

Each line is one global and the evidence the listing gives about it: how many bodies read it through a cast (and at
which width), how many take its address and hand it to which kind of callee, and the first bytes of the image at that
address. Nothing here decides a type - it lays out what the binary says so the pass can decide with evidence in hand.
"""
import glob, re, struct, collections

IMG = "/app/co_decomp/orig_binaries/Source/NpcServer.exe"
CASTE = re.compile(r"\*\s*\(\s*([A-Za-z0-9_ ]+?)\s*\*\s*\)\s*\(\s*(DAT_[0-9a-f]{9})")
DROP = re.compile(r"\b(DAT_[0-9a-f]{9})\b")


def image():
    data = open(IMG, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    n = struct.unpack_from("<H", data, pe + 6)[0]
    optsz = struct.unpack_from("<H", data, pe + 0x14)[0]
    base = struct.unpack_from("<Q", data, pe + 0x18 + 24)[0]
    secs = [struct.unpack_from("<IIII", data, pe + 0x18 + optsz + i * 40 + 8) for i in range(n)]
    return data, base, secs


def peek(data, base, secs, va, n=24):
    r = va - base
    for vsz, sva, rsz, rp in secs:
        if sva <= r < sva + max(vsz, rsz):
            b = data[rp + r - sva:rp + r - sva + n]
            return " ".join("%02x" % x for x in b)
    return "(unmapped)"


def main():
    data, base, secs = image()
    casts = collections.defaultdict(collections.Counter)
    address = collections.defaultdict(collections.Counter)
    bodies = collections.Counter()
    for path in glob.glob("Docs/reference/NpcServer_Ghidra/**/*.c*", recursive=True):
        text = open(path, errors="ignore").read()
        for block in re.split(r"(?m)^// ==== ", text):
            fn = block.split("\n", 1)[0].split("@")[-1].strip().split()[0] if "@" in block else "?"
            seen = set()
            for line in block.splitlines():
                for m in CASTE.finditer(line):
                    casts[m.group(2)][m.group(1).strip()] += 1
                for m in re.finditer(r"&\s*(DAT_[0-9a-f]{9})", line):
                    callee = re.findall(r"([A-Za-z_][A-Za-z0-9_:]*)\s*\(", line)
                    address[m.group(1)][callee[0] if callee else "?"] += 1
                for m in DROP.finditer(line):
                    if m.group(1) not in seen:
                        seen.add(m.group(1))
                        bodies[m.group(1)] += 1
    rows = []
    for name in sorted(set(casts) | set(address) | set(bodies)):
        va = int(name[4:], 16)
        c = casts[name]
        a = address[name]
        rows.append((bodies[name], name, va, c, a))
    rows.sort(reverse=True)
    out = ["# Typing worksheet for the globals", "",
           "Generated by `tools/type_worksheet.py`. Per global: how many bodies mention it, every cast the listing",
           "applies straight to it, every callee it is passed to by address, and the raw bytes at its address.",
           "", "| bodies | global | read as | passed as &X to | first bytes |", "|---|---|---|---|---|"]
    for n, name, va, c, a in rows:
        cast_txt = ", ".join("%s x%d" % (t, k) for t, k in c.most_common()) or "-"
        addr_txt = ", ".join("%s x%d" % (t, k) for t, k in a.most_common(3)) or "-"
        out.append("| %d | `%s` | %s | %s | `%s` |" % (n, name, cast_txt, addr_txt, peek(data, base, secs, va)))
    open("Docs/NPC_DATA_TYPING.md", "w").write("\n".join(out) + "\n")
    print("%d globals, %d with a cast, %d only by address"
          % (len(rows), sum(1 for r in rows if r[3]), sum(1 for r in rows if not r[3])))


if __name__ == "__main__":
    main()
