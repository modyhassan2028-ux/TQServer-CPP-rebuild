#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""dll_inventory.py — per-binary inventory of the whole original build.

For every decompiled binary it reports, straight from the bytes (no inference):
  * decompiled function count
  * the __FILE__ source paths the binary itself embeds
  * the classes whose RTTI type descriptor is present
  * whether the port tree already has a directory for it and how many of the
    embedded source paths already exist as files

Output: Docs/DLL_FULL_INVENTORY.md
"""
import os, re, glob, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

DEC_DIR = "/app/co_decomp/Native-Decompiled"
BIN_DIR = "/app/co_decomp/orig_binaries/Source"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "Docs", "DLL_FULL_INVENTORY.md")

PATH_RE = re.compile(rb"[ -~]{4,120}\.(?:cpp|hpp|h|c)\b")


def embedded_paths(data):
    out = set()
    for m in PATH_RE.finditer(data):
        s = m.group(0).decode("latin-1")
        if "/" in s or "\\" in s:
            out.add(s.replace("\\", "/"))
    return sorted(out)


def rtti_classes(data):
    """Class names carried by RTTI type descriptors (.?AV...@@)."""
    names = set()
    for m in re.finditer(rb"\.\?A[VU]\w*@[ -~]{2,120}", data):
        raw = m.group(0).decode("latin-1")
        parts = []
        for chunk in raw.split("@")[1:]:
            if not chunk:
                break
            parts.append(chunk.rstrip("?") if chunk.endswith("?") else chunk)
        name = "::".join(reversed([p for p in parts if p]))
        if name:
            names.add(name)
    return sorted(names)


def main():
    rows = []
    for f in sorted(glob.glob(os.path.join(DEC_DIR, "*.decompiled.c"))):
        binf = os.path.basename(f)[: -len(".decompiled.c")]
        src = os.path.join(BIN_DIR, binf)
        data = open(src, "rb").read() if os.path.exists(src) else b""
        nfunc = open(f, encoding="utf-8", errors="ignore").read().count("// Function: ")
        paths = embedded_paths(data)
        classes = rtti_classes(data)
        pkg = binf.split(".")[0].lower()
        pkgdir = os.path.join(REPO, "modules", pkg)
        have = 0
        for p in paths:
            # modules/<pkg>/src/<basename> or the flat name anywhere in the tree
            if os.path.exists(os.path.join(pkgdir, "src", os.path.basename(p))):
                have += 1
        rows.append(dict(bin=binf, funcs=nfunc, paths=paths, classes=classes,
                         pkg=pkg, pkgdir=os.path.isdir(pkgdir), have=have))

    tot_f = sum(r["funcs"] for r in rows)
    tot_p = sum(len(r["paths"]) for r in rows)
    with open(OUT, "w", encoding="utf-8") as o:
        o.write("# Full binary inventory (extracted from the binaries)\n\n")
        o.write("Generated by `tools/dll_inventory.py`. Every number below comes "
                "from the binary itself: the decompiled function count, the "
                "`__FILE__` source paths it embeds, and its RTTI class names.\n\n")
        o.write(f"Binaries: **{len(rows)}** · decompiled functions: **{tot_f:,}** · "
                f"embedded source paths: **{tot_p:,}**\n\n")
        o.write("| binary | functions | classes | source paths | port dir | files present |\n")
        o.write("|---|---:|---:|---:|---|---:|\n")
        for r in sorted(rows, key=lambda r: -r["funcs"]):
            o.write(f"| `{r['bin']}` | {r['funcs']:,} | {len(r['classes'])} | "
                    f"{len(r['paths'])} | {'yes' if r['pkgdir'] else 'no'} | "
                    f"{r['have']}/{len(r['paths'])} |\n")
        o.write("\n## Embedded source tree per binary\n\n")
        for r in sorted(rows, key=lambda r: r["bin"]):
            if not r["paths"]:
                continue
            o.write(f"### {r['bin']}\n\n")
            for p in r["paths"]:
                mark = "present" if os.path.exists(
                    os.path.join(REPO, "modules", r["pkg"], "src", os.path.basename(p))
                ) else "missing"
                o.write(f"- `{p}` — {mark}\n")
            o.write("\n")
        o.write("## RTTI classes per binary\n\n")
        for r in sorted(rows, key=lambda r: r["bin"]):
            if not r["classes"]:
                continue
            o.write(f"### {r['bin']} ({len(r['classes'])})\n\n")
            o.write(", ".join(f"`{c}`" for c in r["classes"]) + "\n\n")
    print(f"wrote {OUT}")
    for r in sorted(rows, key=lambda r: -r["funcs"])[:12]:
        print(f"{r['bin']:24} {r['funcs']:6} funcs  {len(r['paths']):3} paths  "
              f"{r['have']}/{len(r['paths'])} present")


if __name__ == "__main__":
    main()
