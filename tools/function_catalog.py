#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""function_catalog.py — catalogue the functions of one binary against the port.

For each decompiled function it records, straight from the decompiled body:
  address, size, whether the body is an import/CRT thunk, the other functions it
  calls, the string literals it passes, and whether the port already references
  the address.  Output: Docs/<BIN>_REMAINING.md

Usage: python3 tools/function_catalog.py Flower.dll
"""
import os, re, sys, glob

DEC = "/app/co_decomp/Native-Decompiled"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    binf = sys.argv[1] if len(sys.argv) > 1 else "Flower.dll"
    pkg = binf.split(".")[0].lower()
    body_src = open(os.path.join(DEC, binf + ".decompiled.c"),
                    encoding="utf-8", errors="ignore").read()
    idx = [l.split("\t") for l in
           open(os.path.join(DEC, binf + ".index.tsv")).read().splitlines()[1:]
           if l.strip()]
    port_txt = ""
    for f in glob.glob(os.path.join(REPO, "modules", pkg, "**", "*.*"),
                       recursive=True) + \
             glob.glob(os.path.join(REPO, "tests", pkg + "_*")):
        try:
            port_txt += open(f, encoding="utf-8", errors="ignore").read()
        except OSError:
            pass
    port_txt = port_txt.lower()

    funcs = {}
    for m in re.finditer(r"// Function: (\S+) @ ([0-9a-f]+)\n// =+\n\n(.*?)\n\n\n",
                         body_src, re.S):
        funcs[m.group(2).lower()] = (m.group(1), m.group(3))

    out = os.path.join(REPO, "Docs", pkg.upper() + "_REMAINING.md")
    rows = []
    for name, addr, size, _st in [(r[0], r[1].lower(), int(r[2]), r[3]) for r in idx]:
        fname, body = funcs.get(addr, ("FUN_" + addr, ""))
        thunk = "Treating indirect jump as call" in body
        callees = sorted({c for c in re.findall(r"FUN_([0-9a-f]{8,})", body)
                          if c.lower() != addr})
        strings = sorted(set(re.findall(r'"([ -~]{3,60})"', body)))
        rows.append(dict(addr=addr, size=size, thunk=thunk, callees=callees,
                         strings=strings, inport=addr in port_txt,
                         head=body.strip().split("\n")[0][:90]))
    done = [r for r in rows if r["inport"]]
    left = [r for r in rows if not r["inport"]]

    with open(out, "w", encoding="utf-8") as o:
        o.write(f"# {binf} — remaining functions\n\n")
        o.write("Generated by `tools/function_catalog.py` from the decompiled "
                "bodies (no inference).\n\n")
        o.write(f"total **{len(rows)}** · referenced by the port **{len(done)}** "
                f"· remaining **{len(left)}** · remaining bytes "
                f"{sum(r['size'] for r in left):,}\n\n")
        o.write(f"of the remaining: import/CRT thunks **{sum(1 for r in left if r['thunk'])}** "
                f"· real bodies **{sum(1 for r in left if not r['thunk'])}**\n\n")
        o.write("## Real bodies still to port (largest first)\n\n")
        o.write("| address | bytes | callees | strings |\n|---|---:|---:|---|\n")
        for r in sorted([r for r in left if not r["thunk"]],
                        key=lambda r: -r["size"]):
            o.write(f"| `0x{r['addr']}` | {r['size']} | {len(r['callees'])} | "
                    f"{', '.join('`' + s + '`' for s in r['strings'][:3])} |\n")
        o.write("\n## Import / CRT thunks still to wire\n\n")
        for r in sorted([r for r in left if r["thunk"]], key=lambda r: r["addr"]):
            o.write(f"- `0x{r['addr']}` ({r['size']} B) `{r['head']}`\n")
    print(f"wrote {out}: {len(left)} remaining "
          f"({sum(1 for r in left if r['thunk'])} thunks, "
          f"{sum(1 for r in left if not r['thunk'])} real)")


if __name__ == "__main__":
    main()
