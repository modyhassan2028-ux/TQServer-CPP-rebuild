#!/usr/bin/env python3
"""Write Docs/<PKG>_IMPORTS.md: every import trampoline and the symbol it jumps
to, resolved from the PE import directory of the binary itself. A trampoline is
a body of ten bytes or less that the decompiler reports as an indirect jump."""
import os
import re
import struct
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEC = "/app/co_decomp/Native-Decompiled"
BIN = "/app/work/orig_extract/Source"


class PE:
    def __init__(self, f):
        self.f = f
        pe = struct.unpack_from("<I", f, 0x3C)[0]
        nsec = struct.unpack_from("<H", f, pe + 6)[0]
        opt = pe + 24
        self.base = struct.unpack_from("<Q", f, opt + 24)[0]
        ddir = opt + 112                              # data directories
        self.imp_rva, self.imp_size = struct.unpack_from("<II", f, ddir + 8 * 1)
        sect = opt + struct.unpack_from("<H", f, pe + 20)[0]
        self.secs = []
        for i in range(nsec):
            o = sect + i * 40
            vs, va = struct.unpack_from("<II", f, o + 8)
            rs, ra = struct.unpack_from("<II", f, o + 16)
            self.secs.append((va, vs, ra, rs))

    def off(self, rva):
        for va, vs, ra, rs in self.secs:
            if va <= rva < va + max(vs, rs):
                return ra + (rva - va)
        return None

    def cstr(self, rva):
        o = self.off(rva)
        if o is None:
            return None
        e = self.f.index(b"\0", o)
        return self.f[o:e].decode("ascii", "replace")

    def imports(self):
        """IAT slot VA -> (dll, symbol)."""
        out = {}
        f = self.f
        o = self.off(self.imp_rva)
        if o is None:
            return out
        while True:
            ilt, _ts, _fwd, name_rva, iat = struct.unpack_from("<IIIII", f, o)
            if name_rva == 0 and iat == 0:
                break
            dll = self.cstr(name_rva) or "?"
            i = 0
            while True:
                slot = self.off((ilt or iat) + i * 8)
                if slot is None:
                    break
                v = struct.unpack_from("<Q", f, slot)[0]
                if v == 0:
                    break
                if v & 0x8000000000000000:
                    sym = f"ordinal {v & 0xFFFF}"
                else:
                    sym = self.cstr((v & 0x7FFFFFFF) + 2) or "?"
                out[self.base + iat + i * 8] = (dll, sym)
                i += 1
            o += 20
        return out


def main():
    pkg = sys.argv[1] if len(sys.argv) > 1 else "Flower.dll"
    base_pkg = pkg.split(".")[0]
    f = open(os.path.join(BIN, pkg), "rb")
    data = f.read()
    pe = PE(open(os.path.join(BIN, pkg), "rb").read())
    iat = pe.imports()

    idx = [l.split("\t") for l in
           open(os.path.join(DEC, pkg + ".index.tsv")).read().splitlines()[1:]
           if l.strip()]
    body_src = open(os.path.join(DEC, pkg + ".decompiled.c"),
                    encoding="utf-8", errors="ignore").read()

    rows = []
    unresolved = []
    for r in idx:
        addr, size, name = r[1].lower(), int(r[2]), r[0]
        if size > 10:
            continue
        rva = int(addr, 16) - pe.base
        o = pe.off(rva)
        if o is None or o + 6 > len(data):
            continue
        b = data[o:o + 6]
        if b[0:2] != b"\xff\x25":                     # jmp *disp32(%rip)
            continue
        disp = struct.unpack_from("<i", data, o + 2)[0]
        tgt = int(addr, 16) + 6 + disp
        if tgt in iat:
            dll, sym = iat[tgt]
            rows.append((addr, size, name, dll, sym, tgt))
        else:
            unresolved.append((addr, size, name))
    out = os.path.join(REPO, "Docs", base_pkg.upper() + "_IMPORTS.md")
    with open(out, "w", encoding="utf-8") as o:
        o.write(f"# {pkg} — the import trampolines\n\n")
        o.write("Generated by `tools/import_map.py` from the PE import directory "
                "of the binary: each row decodes the trampoline's "
                "`jmp *disp32(%rip)` and reads the slot it lands on, so the "
                "symbol is the one the loader binds at run time.\n\n")
        o.write(f"{len(rows)} trampolines resolved"
                + (f", {len(unresolved)} not bound through the import table"
                   if unresolved else "") + ".\n\n")
        o.write("| address | bytes | index name | dll | symbol |\n|---|---:|---|---|---|\n")
        for addr, size, name, dll, sym, _tgt in sorted(rows):
            o.write(f"| `0x{addr}` | {size} | `{name}` | {dll} | `{sym}` |\n")
        if unresolved:
            o.write("\n## Not bound through the import table\n\n")
            for addr, size, name in sorted(unresolved):
                o.write(f"- `0x{addr}` ({size} B) `{name}`\n")
        o.write("\nIn the port a resolved trampoline is the CRT or platform "
                "symbol in the last column: call sites use that symbol "
                "directly, and a `g_pfn*` seam stands in where the host has to "
                "supply it.\n")
    print(f"wrote {out}: {len(rows)} resolved, {len(unresolved)} unresolved")


if __name__ == "__main__":
    main()
