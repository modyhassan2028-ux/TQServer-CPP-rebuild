#!/usr/bin/env python3
"""Turn the leaf shapes of a binary into one generated translation unit.

Every function kept here has a body that is *entirely* one of the templates below, so the
generated body is the binary's own semantics, not an interpretation of it. Each entry carries
its address, and the table lets a single test walk every generated function in turn.
"""
import re, sys, collections

SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/synd_full.txt'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'modules/syndicate/src/genleaf.cpp'

def load(path):
    ins = []
    for line in open(path):
        m = re.match(r'^\s+([0-9a-f]+):\t(.*)$', line)
        if not m: continue
        op = m.group(2).split('#')[0].strip()
        if op.startswith(('int3', 'nop', 'xchg   %ax,%ax', 'data16')): continue
        ins.append((int(m.group(1), 16), op))
    funcs, cur, start, prev = [], [], None, None
    for a, op in ins:
        if prev is not None and a - prev > 16 and cur:
            funcs.append((start, cur)); cur = []
        if not cur: start = a
        cur.append(op); prev = a
        if op.startswith('ret'):
            funcs.append((start, cur)); cur = []
    if cur: funcs.append((start, cur))
    return funcs

Q = r'(?:0x[0-9a-f]+|\(%rip\))'
PATTERNS = [
    ('zero',   re.compile(r'^xor\s+%eax,%eax$'),                              1),
    ('ident',  re.compile(r'^mov\s+(%r[a-z0-9]+),\1$'.replace('%r','%r')),     2),
    ('const',  re.compile(r'^movabs\s+\$0x([0-9a-f]+),%r[a-z0-9]+$'),          2),
    ('const',  re.compile(r'^mov\s+\$0x([0-9a-f]+),%eax$'),                    2),
    ('field',  re.compile(r'^mov\s+0x([0-9a-f]+)\((?!%rip\))%r[a-z0-9]+\),%r[a-z0-9]+$'),2),
    ('lea',    re.compile(r'^lea\s+0x([0-9a-f]+)\((?!%rip\))%r[a-z0-9]+\),%r[a-z0-9]+$'),2),
    ('store0', re.compile(r'^movq\s+\$0x0,\(%r[a-z0-9]+\)$'),                  2),
]
def classify(body):
    """None unless the whole body is one template plus an optional zero-store / return."""
    b = list(body)
    if b in (['ret'], ['ret    $0x0'], ['ret    $0x8'], ['repz ret'], ['nop']):
        return ('empty', 0, 0)
    kind = None; arg = 0
    if len(b) >= 1:
        for name, rx, _n in PATTERNS:
            m = rx.match(b[0])
            if m:
                kind = name
                arg = int(m.group(1), 16) if m.groups() else 0
                b = b[1:]
                break
    if kind is None:
        # a store of zero followed by the identity return is its own shape
        if len(b) == 3 and b[0].startswith('movq   $0x0,(') and re.match(r'^mov\s+%r[a-z0-9]+,%r[a-z0-9]+$', b[1]):
            return ('zeroinit', 0, 0)
        return None
    if b in (['ret'], ['ret    $0x0'], ['ret    $0x8'], ['repz ret']):
        return (kind, arg, 0)
    if kind == 'field' and len(b) == 2 and b[0].startswith('add    $0x') and b[1] in ('ret', 'ret    $0x0'):
        return ('fieldbias', arg, int(b[0].split('$0x')[1].split(',')[0], 16))
    return None

def main():
    funcs = load(SRC)
    seen = {}
    for addr, body in funcs:
        c = classify(body)
        if c: seen[addr] = c
    kinds = collections.Counter(k for k, _a, _b in seen.values())
    lines = ['// GENERATED by tools/family_gen.py from the binary — do not hand edit.',
             '// Every body below is one of the leaf shapes: the whole function is the template.',
             '#include <cstdint>', '', 'namespace tq {', '']
    table = []
    bias_of = lambda a, _s=seen: _s[a][2]
    for addr in sorted(seen):
        kind, arg, bias = seen[addr]
        name = 'SynLeaf_%x' % addr
        if kind == 'empty':
            body = 'return p;'
        elif kind == 'zero':
            body = 'return nullptr;'
        elif kind == 'ident':
            body = 'return p;'
        elif kind == 'const':
            body = 'return (void*)(uintptr_t)0x%xULL;' % arg
        elif kind == 'field':
            body = 'return *(void**)((unsigned char*)p + 0x%x);' % arg
        elif kind == 'fieldbias':
            body = 'return (void*)((unsigned char*)(*(void**)((unsigned char*)p + 0x%x)) + 0x%x);' % (arg, bias)
        elif kind == 'lea':
            body = 'return (void*)((unsigned char*)p + 0x%x);' % arg
        elif kind == 'zeroinit':
            body = '*(void**)p = nullptr; return p;'
        else:
            continue
        lines.append('void* %s(void* p) { %s }' % (name, body))
        table.append((addr, kind, arg, name))
    lines.append('')
    lines.append('// kind codes: 0 empty, 1 zero, 2 identity, 3 constant, 4 field, 5 field+bias, 6 lea, 7 zero-store')
    KN = {'empty': 0, 'zero': 1, 'ident': 2, 'const': 3, 'field': 4, 'fieldbias': 5, 'lea': 6, 'zeroinit': 7}
    lines.append('const SynLeafEntry g_synLeafTable[] = {')
    for addr, kind, arg, name in table:
        lines.append('    { 0x%xu, %d, 0x%xu, 0x%xu, %s },' % (addr, KN[kind], arg, bias_of(addr), name))
    lines.append('};')
    lines.append('const unsigned int g_synLeafCount = %du;' % len(table))
    lines.append('')
    lines.append('}  // namespace tq')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('generated', len(table), 'bodies from', len(funcs), 'functions')
    for k, c in kinds.most_common():
        print('   %-10s %5d' % (k, c))

main()
