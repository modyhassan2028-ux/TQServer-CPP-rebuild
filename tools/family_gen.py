#!/usr/bin/env python3
"""Turn the leaf shapes of a binary into one generated translation unit.

Every function kept here has a body that is *entirely* one of the templates below, so the
generated body is the binary's own semantics, not an interpretation of it. Each entry carries
its address, and the table lets a single test walk every generated function in turn.
"""
import re, sys, collections

SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/synd_full.txt'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'modules/syndicate/src/genleaf.cpp'

def load(path):
    ins = []
    for line in open(path):
        m = re.match(r'^\s+([0-9a-f]+):\t(.*)$', line)
        if not m: continue
        raw = m.group(2)
        op = raw.split('#')[0].strip()
        if op.startswith(('int3', 'nop', 'xchg   %ax,%ax', 'data16')): continue
        tgt = None
        mm = re.search(r'#\s*0x([0-9a-f]+)', raw)
        if mm: tgt = int(mm.group(1), 16)
        ins.append((int(m.group(1), 16), op, tgt))
    funcs, cur, start, prev = [], [], None, None
    for a, op, tgt in ins:
        if prev is not None and a - prev > 16 and cur:
            funcs.append((start, cur)); cur = []
        if not cur: start = a
        cur.append((op, tgt)); prev = a
        if op.startswith('ret') or op.startswith('jmp'):
            funcs.append((start, cur)); cur = []
    if cur: funcs.append((start, cur))
    return funcs

Q = r'(?:0x[0-9a-f]+|\(%rip\))'
PATTERNS = [
    ('zero',   re.compile(r'^xor\s+%eax,%eax$'),                              1),
    ('ident',  re.compile(r'^mov\s+(%r[a-z0-9]+),\1$'.replace('%r','%r')),     2),
    ('const',  re.compile(r'^movabs\s+\$0x([0-9a-f]+),%r[a-z0-9]+$'),          2),
    ('const',  re.compile(r'^mov\s+\$0x([0-9a-f]+),%eax$'),                    2),
    ('field',  re.compile(r'^mov\s+0x([0-9a-f]+)\((?!%rip\))%r[a-z0-9]+\),%r[a-z0-9]+$'),2),
    ('lea',    re.compile(r'^lea\s+0x([0-9a-f]+)\((?!%rip\))%r[a-z0-9]+\),%r[a-z0-9]+$'),2),
    ('store0', re.compile(r'^movq\s+\$0x0,\(%r[a-z0-9]+\)$'),                  2),
]
def classify(body, start=None):
    if len(body) == 1 and body[0][0].startswith('jmp    *') and body[0][1] is not None:
        return ('slot', body[0][1], 0)
    """None unless the whole body is one template plus an optional zero-store / return."""
    if len(body) == 1 and body[0][0].startswith('jmp') and body[0][1] is not None \
            and start is not None and body[0][1] > start:
        return ('tail', body[0][1], 0)
    b = [op for op, _t in body]
    if b in (['ret'], ['ret    $0x0'], ['ret    $0x8'], ['repz ret'], ['nop']):
        return ('empty', 0, 0)
    kind = None; arg = 0
    if len(b) >= 1:
        for name, rx, _n in PATTERNS:
            m = rx.match(b[0])
            if m:
                kind = name
                arg = int(m.group(1), 16) if m.groups() else 0
                b = b[1:]
                break
    if kind is None:
        # a store of zero followed by the identity return is its own shape
        if len(b) == 3 and b[0].startswith('movq   $0x0,(') and re.match(r'^mov\s+%r[a-z0-9]+,%r[a-z0-9]+$', b[1]):
            return ('zeroinit', 0, 0)
        return None
    if b in (['ret'], ['ret    $0x0'], ['ret    $0x8'], ['repz ret']):
        return (kind, arg, 0)
    if kind == 'field' and len(b) == 2 and b[0].startswith('add    $0x') and b[1] in ('ret', 'ret    $0x0'):
        return ('fieldbias', arg, int(b[0].split('$0x')[1].split(',')[0], 16))
    return None

def main():
    funcs = load(SRC)
    seen = {}
    for addr, body in funcs:
        c = classify(body, addr)
        if c: seen[addr] = c
    kinds = collections.Counter(k for k, _a, _b in seen.values())
    slots = sorted({a for k, a, _b in seen.values() if k == 'slot'})
    out = ['// GENERATED by tools/family_gen.py from the binary - do not hand edit.',
           '// Every body is one leaf template in its entirety; nothing here is an interpretation.',
           '#include <cstdint>',
           '#include "modules/syndicate/src/genleaf.h"',
           '',
           'namespace tq {',
           '',
           '// The forwarder family forwards the four integer argument registers to its target address.',
           '// Float registers are not carried; that limit is recorded in Docs/TPL_FAMILIES.md.',
           'void* (*g_pfnSynTailCall)(unsigned long long uTarget, void* a1, void* a2, void* a3, void* a4) = nullptr;',
           '',
           '// The slot family is one seam per indirect slot the image jumps through.',
           'const unsigned long long g_synSlotAddr[] = {']
    out.append('    ' + ', '.join('0x%xULL' % s for s in slots) + ',')
    out.append('};')
    out.append('const unsigned int g_synSlotCount = %du;' % len(slots))
    out.append('void* (*g_synSlotFn[%d])(void*, void*, void*, void*) = { nullptr };' % max(len(slots), 1))
    out.append('')
    out.append('static unsigned int SynSlotIndex(unsigned long long uAddr) {')
    out.append('    for (unsigned int i = 0; i < g_synSlotCount; ++i)')
    out.append('        if (g_synSlotAddr[i] == uAddr) return i;')
    out.append('    return ~0u;')
    out.append('}')
    out.append('')
    KN = {'empty': 0, 'zero': 1, 'ident': 2, 'const': 3, 'field': 4,
          'fieldbias': 5, 'lea': 6, 'zeroinit': 7, 'tail': 8, 'slot': 9}
    table = []
    for addr in sorted(seen):
        kind, arg, bias = seen[addr]
        if kind == 'slot':
            name = 'SynSlotThunk_%x' % addr
            out.append('void* %s(void* a1, void* a2, void* a3, void* a4) {' % name)
            out.append('    unsigned int i = SynSlotIndex(0x%xULL);' % arg)
            out.append('    if (i == ~0u || g_synSlotFn[i] == nullptr) return nullptr;')
            out.append('    return g_synSlotFn[i](a1, a2, a3, a4);')
            out.append('}')
        elif kind == 'tail':
            name = 'SynThunk_%x' % addr
            out.append('void* %s(void* a1, void* a2, void* a3, void* a4) {' % name)
            out.append('    if (g_pfnSynTailCall == nullptr) return nullptr;')
            out.append('    return g_pfnSynTailCall(0x%xULL, a1, a2, a3, a4);' % arg)
            out.append('}')
        else:
            name = 'SynLeaf_%x' % addr
            body = {'empty': 'return p;', 'zero': 'return nullptr;', 'ident': 'return p;',
                    'const': 'return (void*)(uintptr_t)0x%xULL;' % arg,
                    'field': 'return *(void**)((unsigned char*)p + 0x%x);' % arg,
                    'fieldbias': 'return (void*)((unsigned char*)(*(void**)((unsigned char*)p + 0x%x)) + 0x%x);' % (arg, bias),
                    'lea': 'return (void*)((unsigned char*)p + 0x%x);' % arg,
                    'zeroinit': '*(void**)p = nullptr; return p;'}[kind]
            out.append('void* %s(void* p) { %s }' % (name, body))
        table.append((addr, kind, arg, bias, name))
    out.append('')
    out.append('// kinds: 0 empty, 1 zero, 2 identity, 3 constant, 4 field, 5 field+bias, 6 lea, 7 zero-store, 8 forward, 9 slot')
    out.append('const SynLeafEntry g_synLeafTable[] = {')
    for addr, kind, arg, bias, name in table:
        slot = '(void* (*)(void*))%s' % name if kind in ('tail', 'slot') else name
        out.append('    { 0x%xULL, %d, 0x%xULL, 0x%xULL, %s },' % (addr, KN[kind], arg, bias, slot))
    out.append('};')
    out.append('const unsigned int g_synLeafCount = %du;' % len(table))
    out.append('')
    out.append('}  // namespace tq')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('generated', len(table), 'bodies from', len(funcs), 'functions;', len(slots), 'slots')
    for k, c in kinds.most_common():
        print('   %-10s %5d' % (k, c))

main()
