#!/usr/bin/env python3
"""Turn the small functions of a module into C++ one-liners straight from the
instructions. Nothing is inferred: each unit is matched against an exact assembly
shape, and the assembly itself is kept beside it as the evidence.

usage: gen_small_units.py <module.dll> <out.cpp> [max_size_hex]"""
import re, subprocess, sys, collections

MOD = sys.argv[1]
OUT = sys.argv[2]
MAX = int(sys.argv[3], 16) if len(sys.argv) > 3 else 0x40
DLL = f'/app/work/orig_extract/Source/{MOD}'
IDX = f'/app/co_decomp/Native-Decompiled/{MOD}.index.tsv'

sizes = {}
for l in open(IDX, errors='ignore'):
    p = l.rstrip('\n').split('\t')
    if len(p) >= 4 and p[2].isdigit():
        sizes[int(p[1], 16)] = int(p[2])
addrs = sorted(a for a, s in sizes.items() if s <= MAX and s > 0)

text = subprocess.run(['objdump', '-d', '-M', 'intel', '--no-show-raw-insn', DLL],
                      capture_output=True, text=True).stdout
flat = []
for line in text.split('\n'):
    m = re.match(r'^\s+([0-9a-f]{6,16}):\s+(\S+)\s*(.*)$', line)
    if m:
        flat.append((int(m.group(1), 16), m.group(2), m.group(3).strip()))
flat.sort()
flat_addrs = [x[0] for x in flat]
import bisect

def body_of(a, size):
    i = bisect.bisect_left(flat_addrs, a)
    out = []
    while i < len(flat) and flat[i][0] < a + size:
        out.append(flat[i]); i += 1
    return out

KIND = collections.Counter()
units = []
for a in addrs:
    body = body_of(a, sizes[a])
    if not body:
        KIND['no-disassembly'] += 1; continue
    ops = [f'{m} {o}'.strip() for _, m, o in body]
    shape = None
    if len(ops) == 2 and ops[1] == 'ret':
        o = ops[0]
        if o == 'mov rax,rcx': shape = ('this', None)
        elif o == 'xor eax,eax': shape = ('zero', None)
        elif re.fullmatch(r'mov eax,0x[0-9a-f]+', o): shape = ('const', int(o.split(',')[1], 16))
        elif m := re.fullmatch(r'mov rax,QWORD PTR \[rcx(?:(\+0x[0-9a-f]+))?\]', o):
            shape = ('read8', int(m.group(1), 16) if m.group(1) else 0)
        elif m := re.fullmatch(r'mov eax,DWORD PTR \[rcx(?:(\+0x[0-9a-f]+))?\]', o):
            shape = ('read4', int(m.group(1), 16) if m.group(1) else 0)
        elif m := re.fullmatch(r'mov rax,QWORD PTR \[rip\+0x[0-9a-f]+\]\s*#\s*([0-9a-f]+)', o):
            shape = ('global8', int(m.group(1), 16))
        elif m := re.fullmatch(r'lea rax,\[rip\+0x[0-9a-f]+\]\s*#\s*([0-9a-f]+)', o):
            shape = ('addr', int(m.group(1), 16))
    elif len(ops) == 2 and ops[0].startswith('jmp '):
        t = re.fullmatch(r'jmp\s+([0-9a-f]+)', ops[0])
        if t: shape = ('jmp', int(t.group(1), 16))
    if shape is None:
        KIND['unmatched'] += 1; continue
    KIND[shape[0]] += 1
    units.append((a, sizes[a], shape, ops))

with open(OUT, 'w') as f:
    f.write(f'// ============================================================================\n')
    f.write(f'// {MOD} · the small units, generated from the instructions of the binary.\n')
    f.write(f'//   Every line below is one function of {MAX:#x} bytes or less, matched against an exact\n')
    f.write(f'//   assembly shape; the instructions are kept beside each unit so the match is auditable.\n')
    f.write(f'//   Generated by tools/gen_small_units.py, do not edit by hand.\n')
    f.write(f'// ============================================================================\n')
    f.write('#include <cstdint>\n\nnamespace tq {\n\n')
    f.write('using u8 = uint8_t; using u32 = uint32_t; using u64 = uint64_t;\n\n')
    f.write('struct SynAddr { uintptr_t uAddress; const char* pszKind; };\n\n')
    for a, s, shape, ops in units:
        ev = '; '.join(x.replace('  ', ' ') for x in ops)
        k = shape[0]
        if k == 'this':
            f.write(f'inline void* Fn{a:X}(void* pThis) {{ return pThis; }}   // {ev}\n')
        elif k == 'zero':
            f.write(f'inline u64 Fn{a:X}(void*) {{ return 0; }}   // {ev}\n')
        elif k == 'const':
            f.write(f'inline u64 Fn{a:X}(void*) {{ return {shape[1]:#x}; }}   // {ev}\n')
        elif k == 'read8':
            f.write(f'inline u64 Fn{a:X}(void* p) {{ return *(const u64*)((const char*)p + {shape[1]:#x}); }}   // {ev}\n')
        elif k == 'read4':
            f.write(f'inline u32 Fn{a:X}(void* p) {{ return *(const u32*)((const char*)p + {shape[1]:#x}); }}   // {ev}\n')
        elif k == 'global8':
            f.write(f'u64* Fn{a:X}();   // {ev} — the global at {shape[1]:#x}\n')
        elif k == 'addr':
            f.write(f'const void* Fn{a:X}();   // {ev} — the literal at {shape[1]:#x}\n')
        elif k == 'jmp':
            f.write(f'// Fn{a:X} jumps straight to {shape[1]:#x}   // {ev}\n')
    f.write('\n}  // namespace tq\n')

print(f'{MOD}: {len(addrs)} functions <= {MAX:#x}')
for k, n in KIND.most_common(): print(f'   {k:14s} {n}')
print(f'   emitted {len(units)} units to {OUT}')
