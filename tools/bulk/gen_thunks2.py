#!/usr/bin/env python3
"""Second wave of transcribed wrapper families (C and D), appended to the generated headers.

Family D:  push rbp ; sub ; mov rbp,rdx ; lea rcx,[rbp+off] ; call T      -> T(this+off)
Family C:  spill ; push rbp ; sub ; mov rbp,rdx ; mov rcx,[rbp+off] ; call T1 ;
           xor edx,edx ; xor ecx,ecx ; call T2                            -> T1(member); T2(0,0)
Whole-body matches only; offsets and targets are transcribed.
"""
import json, re, os

funcs = json.load(open('tools/bulk/funcs.json'))
for f in funcs:
    f['ins'] = [re.sub(r'^rex ', '', ' '.join(t.split())) for t in f['ins']]
blob = ''
for root, d, fs in os.walk('modules'):
    for n in fs:
        if n.endswith(('.cpp', '.h')) and not n.startswith('synthunks'):
            blob += open(os.path.join(root, n), errors='ignore').read().lower()
rem = [f for f in funcs if ('0x%x' % f['a']) not in blob]

D = re.compile(r'push rbp ; sub rsp,0x20 ; mov rbp,rdx ; lea rcx,\[rbp\+(0x[0-9a-f]+)\] ; '
               r'call (0x[0-9a-f]+) ; add rsp,0x20 ; pop rbp ; ret')
C = re.compile(r'mov QWORD PTR \[rsp\+0x10\],rdx ; push rbp ; sub rsp,0x20 ; mov rbp,rdx ; '
               r'mov rcx,QWORD PTR \[rbp\+(0x[0-9a-f]+)\] ; call (0x[0-9a-f]+) ; '
               r'xor edx,edx ; xor ecx,ecx ; call (0x[0-9a-f]+) ; add rsp,0x20 ; pop rbp ; ret')

fam_d, fam_c = [], []
for f in rem:
    body = ' ; '.join(f['ins'])
    m = D.fullmatch(body)
    if m:
        fam_d.append({'a': f['a'], 'off': int(m.group(1), 16), 't': int(m.group(2), 16)}); continue
    m = C.fullmatch(body)
    if m:
        fam_c.append({'a': f['a'], 'off': int(m.group(1), 16), 't1': int(m.group(2), 16),
                      't2': int(m.group(3), 16)})
print('family D %d, family C %d' % (len(fam_d), len(fam_c)))

# ---- headers -----------------------------------------------------------------
def write2(path, guard, banner, decls, lines):
    with open(path, 'w') as fp:
        fp.write('// %s\n// Generated by tools/bulk/gen_thunks2.py — whole-body matches only.\n' % banner)
        fp.write('#ifndef %s\n#define %s\n\n#include <cstdint>\n\nnamespace tq {\n\n' % (guard, guard))
        fp.write('\n'.join(decls) + '\n\n' + '\n'.join(lines) + '\n\n}  // namespace tq\n\n#endif\n')

td = sorted({e['t'] for e in fam_d})
decls = ['extern void* (*g_fnThkD%x)(void* pInterior);' % t for t in td]
lines = []
for t in td:
    lines.append('// ---- calling 0x%x with this+offset' % t)
    for e in [x for x in fam_d if x['t'] == t]:
        lines.append('inline void* SynThkD_%x(void* pUnused, void* pObj) {   // 0x%x\n'
                     '    return g_fnThkD%x((void*)((uint8_t*)pObj + 0x%x));\n}' % (e['a'], e['a'], t, e['off']))
write2('modules/syndicate/src/synthunks_d.h', 'TQ_SYN_THUNKS_D_H',
       'synthunks_d.h — RAW Syndicate.dll v6159 · %d wrappers passing this+offset (family D).' % len(fam_d),
       decls, lines)

tc = sorted({(e['t1'], e['t2']) for e in fam_c})
decls = ['extern void* (*g_fnThkC1_%x_%x)(void* pMember);' % tc_ for tc_ in []]
decls = []
for (t1, t2) in tc:
    decls.append('extern void* (*g_fnThkC1_%x_%x)(void* pMember);   // first call' % (t1, t2))
    decls.append('extern void* (*g_fnThkC2_%x_%x)(void* pUnused, void* pSecond);   // second call' % (t1, t2))
lines = []
for (t1, t2) in tc:
    lines.append('// ---- 0x%x then 0x%x' % (t1, t2))
    for e in [x for x in fam_c if (x['t1'], x['t2']) == (t1, t2)]:
        lines.append('inline void* SynThkC_%x(void* pUnused, void* pObj) {   // 0x%x\n'
                     '    g_fnThkC1_%x_%x(*(void**)((uint8_t*)pObj + 0x%x));\n'
                     '    return g_fnThkC2_%x_%x(nullptr, nullptr);\n}'
                     % (e['a'], e['a'], t1, t2, e['off'], t1, t2))
write2('modules/syndicate/src/synthunks_c.h', 'TQ_SYN_THUNKS_C_H',
       'synthunks_c.h — RAW Syndicate.dll v6159 · %d wrappers that release a member then call with nulls (family C).' % len(fam_c),
       decls, lines)

json.dump({'d': fam_d, 'c': fam_c}, open('tools/bulk/manifest2.json', 'w'))
