#!/usr/bin/env python3
"""Emit the table the smoke harness walks: every lifted body, by address."""
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HDR = os.path.join(REPO, 'modules/syndicate/src/synlift.h')
OUT = os.path.join(REPO, 'tests/lift_smoke_table.h')


def main():
    hdr = open(HDR).read()
    addrs = sorted({int(a, 16) for a in re.findall(r'SynLift_([0-9a-f]+)\(', hdr)})
    seams = sorted({int(a, 16) for a in re.findall(r'g_fnLIFT_([0-9a-f]+)\b', hdr)} & set(addrs))
    with open(OUT, 'w') as fh:
        fh.write('// Generated by tools/bulk/gen_smoke_table.py - every lifted body, by address.\n')
        fh.write('#pragma once\n#include <cstdint>\n#include "modules/syndicate/src/synlift.h"\n\n')
        fh.write('struct LiftBody { uint64_t addr; uint64_t (*fn)(uint64_t, uint64_t, uint64_t, uint64_t); };\n')
        fh.write('static const LiftBody kLiftBodies[] = {\n')
        for a in addrs:
            fh.write('    { 0x%xULL, &tq::SynLift_%x },\n' % (a, a))
        fh.write('};\n\n')
        fh.write('// A lifted body reaches another routine through g_fnLIFT_<addr>. Binding these to the\n')
        fh.write('// lifted bodies themselves is what lets a run go deeper than one frame.\n')
        fh.write('struct LiftSeam { uint64_t addr; void** slot; void* body; };\n')
        fh.write('static const LiftSeam kLiftSeams[] = {\n')
        for a in seams:
            fh.write('    { 0x%xULL, (void**)&tq::g_fnLIFT_%x, (void*)&tq::SynLift_%x },\n' % (a, a, a))
        fh.write('};\n')
        fh.write('static const unsigned kLiftBodyCount = sizeof(kLiftBodies) / sizeof(kLiftBodies[0]);\n')
        fh.write('static const unsigned kLiftSeamCount = sizeof(kLiftSeams) / sizeof(kLiftSeams[0]);\n')
    print('%d bodies -> %s' % (len(addrs), OUT))


if __name__ == '__main__':
    main()
