#!/usr/bin/env python3
"""Transcribe the repeated wrapper bodies into ports, with a generated equivalence test.

Only whole-body matches are accepted. Every offset and call target is copied from the
instruction text, so no body is inferred; bodies that do not match are left untouched.

Emits:
  modules/syndicate/src/synthunks_a.h     family A: forward one member to a tail call
  modules/syndicate/src/synthunks_b.h     family B: call a target with one or two members of arg2
  tests/cqbase_thunks_test.cpp            one check per generated wrapper
  tools/bulk/manifest.json                what was generated, for the coverage scan
"""
import json, re, os

funcs = json.load(open('tools/bulk/funcs.json'))
for f in funcs:
    f['ins'] = [re.sub(r'^rex ', '', ' '.join(t.split())) for t in f['ins']]

blob = ''
for root, d, fs in os.walk('modules'):
    for n in fs:
        if n.endswith(('.cpp', '.h')) and not n.startswith('synthunks'):
            blob += open(os.path.join(root, n), errors='ignore').read().lower()
rem = [f for f in funcs if ('0x%x' % f['a']) not in blob]
print('remaining after coverage filter:', len(rem))

A = re.compile(r'mov QWORD PTR \[rsp\+0x8\],rcx ; sub rsp,0x([0-9a-f]+) ; '
               r'mov QWORD PTR \[rsp\+0x(?:20|28)\],0xfffffffffffffffe ; '
               r'mov rcx,QWORD PTR \[rcx(?:\+(0x[0-9a-f]+))?\] ; add rsp,0x\1 ; jmp (0x[0-9a-f]+)')
B = re.compile(r'push rbp ; sub rsp,0x20 ; mov rbp,rdx ; '
               r'(?:mov rdx,QWORD PTR \[rbp\+(0x[0-9a-f]+)\] ; )?'
               r'mov rcx,QWORD PTR \[rbp\+(0x[0-9a-f]+)\] ; call (0x[0-9a-f]+) ; '
               r'add rsp,0x20 ; pop rbp ; ret')

fam_a, fam_b = [], []
for f in rem:
    body = ' ; '.join(f['ins'])
    m = A.fullmatch(body)
    if m:
        fam_a.append({'a': f['a'], 'off': int(m.group(2), 16) if m.group(2) else 0,
                      't': int(m.group(3), 16)})
        continue
    m = B.fullmatch(body)
    if m:
        fam_b.append({'a': f['a'], 'o1': int(m.group(1), 16) if m.group(1) else None,
                      'o2': int(m.group(2), 16), 't': int(m.group(3), 16)})

def write(path, guard, banner, decls, lines):
    with open(path, 'w') as fp:
        fp.write('// %s\n' % banner)
        fp.write('// Generated by tools/bulk/gen_thunks.py. Every offset and call target below is\n')
        fp.write('// transcribed from the instruction text of the address on its line.\n')
        fp.write('#ifndef %s\n#define %s\n\n#include <cstdint>\n\nnamespace tq {\n\n' % (guard, guard))
        fp.write('\n'.join(decls) + '\n\n' + '\n'.join(lines) + '\n\n}  // namespace tq\n\n#endif\n')

# ---------------- family A
targets_a = sorted({e['t'] for e in fam_a})
decls = ['// 0x%x : the tail-call target of this whole family\nextern void* (*g_fnThkA%x)(void* pMember);' % (t, t)
         for t in targets_a]
lines = []
for t in targets_a:
    lines.append('// ---- forwarding to 0x%x' % t)
    for e in [x for x in fam_a if x['t'] == t]:
        lines.append('inline void* SynThkA_%x(void* pThis) {   // 0x%x\n'
                     '    return g_fnThkA%x(*(void**)((uint8_t*)pThis + 0x%x));\n}' % (e['a'], e['a'], t, e['off']))
write('modules/syndicate/src/synthunks_a.h', 'TQ_SYN_THUNKS_A_H',
      'synthunks_a.h — RAW Syndicate.dll v6159 · %d wrappers forwarding one member (family A).' % len(fam_a),
      decls, lines)

# ---------------- family B
combos = sorted({(e['t'], e['o1'] is not None) for e in fam_b})
decls = []
for (t, two) in combos:
    decls.append('// 0x%x (%s)\nextern void* (*g_fnThkB%x_%d)(void*%s);'
                 % (t, 'two members' if two else 'one member', t, 1 if two else 0,
                    ', void* pSecond' if two else ''))
lines = []
for (t, two) in combos:
    lines.append('// ---- calling 0x%x' % t)
    for e in [x for x in fam_b if x['t'] == t and (x['o1'] is not None) == two]:
        if two:
            lines.append('inline void* SynThkB_%x(void* pUnused, void* pObj) {   // 0x%x\n'
                         '    return g_fnThkB%x_1(*(void**)((uint8_t*)pObj + 0x%x),\n'
                         '                         *(void**)((uint8_t*)pObj + 0x%x));\n}'
                         % (e['a'], e['a'], t, e['o2'], e['o1']))
        else:
            lines.append('inline void* SynThkB_%x(void* pUnused, void* pObj) {   // 0x%x\n'
                         '    return g_fnThkB%x_0(*(void**)((uint8_t*)pObj + 0x%x));\n}'
                         % (e['a'], e['a'], t, e['o2']))
write('modules/syndicate/src/synthunks_b.h', 'TQ_SYN_THUNKS_B_H',
      'synthunks_b.h — RAW Syndicate.dll v6159 · %d wrappers calling with members of the second argument (family B).' % len(fam_b),
      decls, lines)

json.dump({'a': fam_a, 'b': fam_b}, open('tools/bulk/manifest.json', 'w'))

# ---------------- the generated test
t_a = ['static void* HookA%x(void* pFirst) { g_nTarget = 0x%x; g_v1 = (uintptr_t)pFirst; return (void*)0xBAD; }' % (t, t) for t in targets_a]
one = [t for (t, two) in combos if not two]
two_l = [t for (t, two) in combos if two]
t_b = ['static void* HookB%x_0(void* pFirst) { g_nTarget = 0x%x; g_v1 = (uintptr_t)pFirst; g_v2 = 0; return (void*)0xBAD; }' % (t, t) for t in one]
t_b += ['static void* HookB%x_1(void* pFirst, void* pSecond) { g_nTarget = 0x%x; g_v1 = (uintptr_t)pFirst; g_v2 = (uintptr_t)pSecond; return (void*)0xBAD; }' % (t, t) for t in two_l]

wires = ['    g_fnThkA%x = &HookA%x;' % (t, t) for t in targets_a]
wires += ['    g_fnThkB%x_0 = &HookB%x_0;' % (t, t) for t in one]
wires += ['    g_fnThkB%x_1 = &HookB%x_1;' % (t, t) for t in two_l]

checks = []
for e in fam_a:
    checks.append('    {   // 0x%x\n        SetSentinel(o, 0x%x, 0x1111%04xULL);\n'
                  '        g_nTarget = 0; void* pBack = SynThkA_%x(o);\n'
                  '        CHECK(g_nTarget == 0x%x);\n        CHECK(g_v1 == 0x1111%04xULL);\n'
                  '        CHECK(pBack == (void*)0xBAD);\n    }'
                  % (e['a'], e['off'], e['a'] % 0x10000, e['a'], e['t'], e['a'] % 0x10000))
for e in fam_b:
    if e['o1'] is None:
        checks.append('    {   // 0x%x\n        SetSentinel(o, 0x%x, 0x2222%04xULL);\n'
                      '        g_nTarget = 0; void* pBack = SynThkB_%x(o, o);\n'
                      '        CHECK(g_nTarget == 0x%x);\n        CHECK(g_v1 == 0x2222%04xULL);\n'
                      '        CHECK(pBack == (void*)0xBAD);\n    }'
                      % (e['a'], e['o2'], e['a'] % 0x10000, e['a'], e['t'], e['a'] % 0x10000))
    else:
        checks.append('    {   // 0x%x\n        SetSentinel(o, 0x%x, 0x3333%04xULL);\n'
                      '        SetSentinel(o, 0x%x, 0x4444%04xULL);\n'
                      '        g_nTarget = 0; void* pBack = SynThkB_%x(o, o);\n'
                      '        CHECK(g_nTarget == 0x%x);\n        CHECK(g_v1 == 0x3333%04xULL);\n'
                      '        CHECK(g_v2 == 0x4444%04xULL);\n        CHECK(pBack == (void*)0xBAD);\n    }'
                      % (e['a'], e['o2'], e['a'] % 0x10000, e['o1'], e['a'] % 0x10000,
                         e['a'], e['t'], e['a'] % 0x10000, e['a'] % 0x10000))

with open('tests/cqbase_thunks_test.cpp', 'w') as fp:
    fp.write('// Generated by tools/bulk/gen_thunks.py — one check per transcribed wrapper.\n'
             '// Each wrapper must reach its own target and hand over the members at the offsets the\n'
             '// original body reads, in the original argument order, and pass the answer through.\n')
    fp.write('#include <cstdio>\n#include <cstdlib>\n#include <cstring>\n#include <cstdint>\n\n')
    fp.write('#include "modules/syndicate/src/synthunks_a.h"\n#include "modules/syndicate/src/synthunks_b.h"\n\n')
    fp.write('using namespace tq;\n\nstatic int g_nChecks = 0;\n')
    fp.write('#define CHECK(x) do { ++g_nChecks; if (!(x)) { std::fprintf(stderr, "FAILED %s:%d  %s\\n", __FILE__, __LINE__, #x); std::abort(); } } while (0)\n\n')
    fp.write('static uint64_t g_nTarget = 0; static uintptr_t g_v1 = 0, g_v2 = 0;\n\n')
    fp.write('\n'.join(t_a + t_b) + '\n\n')
    fp.write('static unsigned char g_aBuf[0x1700];   // the largest offset any wrapper reads is 0x1660\n'
             'static void SetSentinel(void*, unsigned off, uint64_t v) { *(uint64_t*)(g_aBuf + off) = v; }\n\n')
    fp.write('int main() {\n' + '\n'.join(wires) + '\n    void* o = g_aBuf;\n\n')
    fp.write('\n'.join(checks) + '\n\n')
    fp.write('    std::printf("SYNDICATE_THUNKS_OK: {0} transcribed wrappers, %d checks\\n", g_nChecks);\n    return 0;\n}}\n'
             .format(len(fam_a) + len(fam_b)))

print('family A %d, family B %d, total %d' % (len(fam_a), len(fam_b), len(fam_a) + len(fam_b)))
