#!/usr/bin/env python3
"""Family CL2 - destroy the subtree rooted at a node (recursive).

Transcribed from 0x1417270a0 (24 instructions):

    if (isNil(node)) return                       // 4-8
    do {
        this->Destroy(node->right)                // 10-12  the call target is this same routine
        rbx = node->left                          // 13
        operator delete(node)                     // 14-15
        node = rbx                                // 17
    } while (!isNil(node))                        // 16-18
"""
import json
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BODY = [(0, 'mov QWORD PTR [rsp+N],rbx'), (1, 'mov QWORD PTR [rsp+N],rsi'),
        (2, 'push rdi'), (3, 'sub rsp,N'),
        (4, 'cmp BYTE PTR [rdx+N],N'), (5, 'mov rdi,rdx'), (6, 'mov rsi,rcx'),
        (7, 'mov rbx,rdx'), (8, 'jne N'), (9, 'xchg ax,ax'),
        (10, 'mov rdx,QWORD PTR [rbx+N]'), (11, 'mov rcx,rsi'), (12, 'call N'),
        (13, 'mov rbx,QWORD PTR [rbx]'), (14, 'mov rcx,rdi'), (15, 'call N'),
        (16, 'cmp BYTE PTR [rbx+N],N'), (17, 'mov rdi,rbx'), (18, 'je N'),
        (19, 'mov rbx,QWORD PTR [rsp+N]'), (20, 'mov rsi,QWORD PTR [rsp+N]'),
        (21, 'add rsp,N'), (22, 'pop rdi'), (23, 'ret')]


def hx(t, i, k=0):
    return int(re.findall(r'0x([0-9a-f]+)', t[i])[k], 16)


def parse(f):
    t = f['text']
    if len(t) != len(BODY):
        return None, 'length %d' % len(t)
    idx = {a: i for i, a in enumerate(f['addr'])}
    for i, pat in BODY:
        if re.sub(r'0x[0-9a-f]+', 'N', t[i]) != pat:
            return None, 'insn %d is %r' % (i, t[i])
    if hx(t, 4) != hx(t, 16):
        return None, 'the nil mark differs between the entry test and the loop test'
    if hx(t, 10) != 0x10:
        return None, 'right link offset is not 0x10'
    m = re.match(r'^call (0x[0-9a-f]+)$', t[12])
    if not m or int(m.group(1), 16) != f['a']:
        return None, 'the recursive call is not to itself'
    if idx.get(int(re.search(r'jne (0x[0-9a-f]+)', t[8]).group(1), 16)) != 19:
        return None, 'the entry branch does not land on the epilogue'
    if idx.get(int(re.search(r'je (0x[0-9a-f]+)', t[18]).group(1), 16)) != 10:
        return None, 'the loop branch does not land on the body'
    return {'a': f['a'], 'mark': hx(t, 4), 'del': hx(t, 15)}, None


def main():
    funcs = json.load(open(os.path.join(REPO, 'tools/bulk/funcs.json')))
    blob = ''
    for root, _, files in os.walk(os.path.join(REPO, 'modules')):
        for n in files:
            if n.endswith(('.cpp', '.h')) and 'synthunks_cl2' not in n:
                blob += open(os.path.join(root, n), errors='ignore').read().lower()
    hits, rej = [], 0
    for f in funcs:
        if ('0x%x' % f['a']) in blob:
            continue
        h, why = parse(f)
        if h:
            hits.append(h)
        elif why and 'length' not in why:
            rej += 1
    hdr = ['// synthunks_cl2.h - generated by tools/bulk/gen_cl2.py - destroy the subtree at a node.',
           '#ifndef SYNTHUNKS_CL2_H', '#define SYNTHUNKS_CL2_H', '',
           '#include <cstdint>', '', 'namespace tq {', '',
           '#define CL2_Q(p, off) (*(void**)((uint8_t*)(p) + (off)))',
           '#define CL2_B(p, off) (*(uint8_t*)((uint8_t*)(p) + (off)))', '']
    dels = sorted({h['del'] for h in hits})
    for d in dels:
        hdr.append('extern void (*g_fnCL2_%x)(void*);' % d)
    hdr.append('')
    for h in hits:
        hdr.append('inline void SynDestroySub_%x(void* pThis, void* pNode) {   // 0x%x' % (h['a'], h['a']))
        hdr.append('    if (CL2_B(pNode, 0x%x) != 0) return;            // insn 4-8: the nil mark' % h['mark'])
        hdr.append('    void* rdi = pNode;                                 // insn 5')
        hdr.append('    void* rbx = pNode;                                 // insn 7')
        hdr.append('    void* rsi = pThis;                                 // insn 6')
        hdr.append('    do {')
        hdr.append('        SynDestroySub_%x(rsi, CL2_Q(rbx, 0x10));       // insn 10-12 (rcx = this, rdx = right)'
                   % h['a'])
        hdr.append('        rbx = CL2_Q(rbx, 0x00);                           // insn 13')
        hdr.append('        g_fnCL2_%x(rdi);                                 // insn 14-15' % h['del'])
        hdr.append('        rdi = rbx;                                        // insn 17')
        hdr.append('    } while (CL2_B(rbx, 0x%x) == 0);                    // insn 16-18' % h['mark'])
        hdr.append('}')
        hdr.append('')
    hdr += ['}  // namespace tq', '', '#undef CL2_Q', '#undef CL2_B', '', '#endif']
    open(os.path.join(REPO, 'modules/syndicate/src/synthunks_cl2.h'), 'w').write('\n'.join(hdr) + '\n')
    src = ['// synthunks_cl2.cpp', '#include "modules/syndicate/src/synthunks_cl2.h"', '', 'namespace tq {', '']
    for d in dels:
        src.append('void (*g_fnCL2_%x)(void*) = nullptr;' % d)
    src += ['', '}  // namespace tq', '']
    open(os.path.join(REPO, 'modules/syndicate/src/synthunks_cl2.cpp'), 'w').write('\n'.join(src))
    json.dump(hits, open(os.path.join(REPO, 'tools/bulk/manifest_cl2.json'), 'w'), indent=1)
    print('family CL2: %d bodies (rejected %d)' % (len(hits), rej))
    print('  marks', sorted({hex(h['mark']) for h in hits}))


if __name__ == '__main__':
    main()
