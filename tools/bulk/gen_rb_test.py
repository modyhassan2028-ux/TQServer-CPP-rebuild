#!/usr/bin/env python3
"""Emits tests/cqbase_thunks_rbf_test.cpp: the same red-black battery for every generated instantiation."""
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
man = json.load(open(os.path.join(REPO, 'tools/bulk/manifest_rb.json')))

HEAD = r'''// Generated by tools/bulk/gen_rb_test.py — red-black insert battery for every instantiation in
// synrbinsert_family.h. Each body gets its own node layout (colour offset C, nil mark C+1) and its own seams.
#include "modules/syndicate/src/synrbinsert_family.h"
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>

using namespace tq;

static int g_checks = 0;
static int g_fails = 0;
static int g_c = 0, g_n = 0;
static int g_used = 0;
static unsigned char g_pool[128][0x80];

#define CHECK(cond) do { ++g_checks; if (!(cond)) { ++g_fails; \
    std::printf("FAILED %s:%d  %s\n", __FUNCTION__, __LINE__, #cond); } } while (0)

static const int OFF_KEY = 0x70;

static inline void* Q(void* p, int off) { return *(void**)((unsigned char*)p + off); }
static inline void S(void* p, int off, void* v) { *(void**)((unsigned char*)p + off) = v; }
static inline unsigned char B(void* p, int off) { return *(unsigned char*)((unsigned char*)p + off); }
static inline int IsNil(void* n) { return B(n, g_n) != 0; }
static inline uint32_t KeyOf(void* n) { return *(uint32_t*)((unsigned char*)n + OFF_KEY); }
static inline int IsRed(void* n) { return B(n, g_c) == 0; }

typedef void* (*InsertFn)(void*, void*, uint8_t, void*, const uint32_t*);
typedef void* (*FactoryFn)(void*, void*, void*, void*, const uint32_t*, uint8_t);

static void* HookFactory(void* a1, void* a2, void* a3, void* a4, const uint32_t* pKey, uint8_t bColour) {
    (void)a1;
    if (g_used >= 128) return nullptr;
    unsigned char* n = g_pool[g_used++];
    std::memset(n, 0xEE, 0x80);
    S(n, 0x00, a2);
    S(n, 0x08, a3);
    S(n, 0x10, a4);
    *(uint32_t*)(n + OFF_KEY) = *pKey;
    B(n, 0);                                   // no-op, keeps the compiler quiet about the helper use order
    *(unsigned char*)(n + g_c) = bColour;
    *(unsigned char*)(n + g_n) = 0;
    return n;
}

static void HookThrow(void) {
    std::printf("unexpected throw seam reached\n");
    std::abort();
}

struct Iter { void* f00; void* f08; };

static int BlackHeight(void* node, void* nil) {
    if (IsNil(node)) {
        CHECK(node == nil);
        return 1;
    }
    if (IsRed(node)) {
        CHECK(!IsRed(Q(node, 0x00)));
        CHECK(!IsRed(Q(node, 0x10)));
    }
    int l = BlackHeight(Q(node, 0x00), nil);
    int r = BlackHeight(Q(node, 0x10), nil);
    CHECK(l == r);
    if (!IsNil(Q(node, 0x00))) CHECK(Q(Q(node, 0x00), 0x08) == node);
    if (!IsNil(Q(node, 0x10))) CHECK(Q(Q(node, 0x10), 0x08) == node);
    return l + (IsRed(node) ? 0 : 1);
}

static void InOrder(void* node, void* nil, std::vector<uint32_t>& out) {
    if (IsNil(node)) return;
    InOrder(Q(node, 0x00), nil, out);
    out.push_back(KeyOf(node));
    InOrder(Q(node, 0x10), nil, out);
}

static void* Extremum(void* node, void* nil, int right) {
    while (!IsNil(Q(node, right ? 0x10 : 0x00))) node = Q(node, right ? 0x10 : 0x00);
    return node;
}

static void RunBody(InsertFn fn, FactoryFn* seam, int C, int N, const char* name) {
    g_c = C; g_n = N; g_used = 0;
    *seam = HookFactory;

    unsigned char db[0x40];
    unsigned char headNode[0x80];
    std::memset(db, 0, sizeof(db));
    std::memset(headNode, 0, sizeof(headNode));
    *(unsigned char*)(headNode + C) = 1;        // the sentinel is black
    *(unsigned char*)(headNode + N) = 1;        // and carries the nil mark
    S(headNode, 0x00, headNode);
    S(headNode, 0x08, nullptr);
    S(headNode, 0x10, headNode);
    S(db, 0x30, headNode);
    *(uint64_t*)(db + 0x38) = 0;

    const uint32_t keys[] = { 50, 30, 70, 20, 40, 60, 80, 10, 45, 65, 90 };
    const int nKeys = (int)(sizeof(keys) / sizeof(keys[0]));
    std::vector<uint32_t> inserted;

    for (int i = 0; i < nKeys; ++i) {
        void* head = Q(db, 0x30);
        void* root = Q(head, 0x08);
        void* parent = head;
        int left = 0;
        if (root != nullptr && !IsNil(root)) {
            void* cur = root;
            for (;;) {
                uint32_t k = KeyOf(cur);
                if (keys[i] < k) {
                    void* c = Q(cur, 0x00);
                    if (IsNil(c)) { parent = cur; left = 1; break; }
                    cur = c;
                } else if (k < keys[i]) {
                    void* c = Q(cur, 0x10);
                    if (IsNil(c)) { parent = cur; left = 0; break; }
                    cur = c;
                } else {
                    CHECK(false);                     // no duplicates in this battery
                    break;
                }
            }
        }
        Iter it = { nullptr, nullptr };
        uint32_t key = keys[i];
        void* r = fn(db, &it, (uint8_t)left, parent, &key);
        CHECK(r == (void*)&it);
        CHECK(it.f00 == Q(db, 0x00));
        CHECK(it.f08 != nullptr);
        CHECK(KeyOf(it.f08) == keys[i]);
        inserted.push_back(keys[i]);

        CHECK(*(uint64_t*)(db + 0x38) == (uint64_t)inserted.size());
        void* newRoot = Q(head, 0x08);
        CHECK(newRoot != nullptr);
        CHECK(!IsRed(newRoot));
        (void)BlackHeight(newRoot, head);
        CHECK(Q(head, 0x00) == Extremum(newRoot, head, 0));
        CHECK(Q(head, 0x10) == Extremum(newRoot, head, 1));

        std::vector<uint32_t> order;
        InOrder(newRoot, head, order);
        std::vector<uint32_t> sorted = inserted;
        for (size_t a = 0; a + 1 < sorted.size(); ++a)
            for (size_t b = a + 1; b < sorted.size(); ++b)
                if (sorted[b] < sorted[a]) { uint32_t t = sorted[a]; sorted[a] = sorted[b]; sorted[b] = t; }
        CHECK(order == sorted);
    }
    (void)name;
}
'''

FOOT = r'''
int main(void) {
'''

def main():
    out = [HEAD, FOOT]
    for i, h in enumerate(man):
        tag = '%x' % h['a']
        out.append('    RunBody(SynRbInsert_%s, &g_fnRB_%s_factory, 0x%x, 0x%x, "0x%s");   // %d' %
                   (tag, tag, h['C'], h['N'], tag, i + 1))
    out.append('')
    out.append('    std::printf("RBF_OK: %d bodies, %%d checks\\n", g_checks);' % len(man))
    out.append('    return g_fails != 0;')
    out.append('}')
    open(os.path.join(REPO, 'tests/cqbase_thunks_rbf_test.cpp'), 'w').write('\n'.join(out) + '\n')
    print('wrote test for %d bodies' % len(man))

if __name__ == '__main__':
    main()
