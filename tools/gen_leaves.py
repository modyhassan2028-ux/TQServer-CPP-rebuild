#!/usr/bin/env python3
"""gen_leaves.py — classify the leaf bodies of a Syndicate.dll range and emit ports.

Only five shapes are accepted, each proved with objdump instruction by instruction:
    off      lea rax,[rcx+N] ; ret                  -> return (uint8_t*)p + N
    id       mov rax,rcx ; ret                       -> return p
    load     mov rax,[rcx+N] ; ret                   -> return *(void**)((uint8_t*)p + N)
    loadadd  mov rax,[rcx+N] ; add rax,M ; ret       -> return *(void**)(p+N) + M
    const    movabs rax,K ; ret                      -> return K
Anything else is left out and reported, never guessed.

usage: gen_leaves.py <hi-hex> <lo-hex> <module-name>
"""
import re, subprocess, sys, glob, os

DLL = '/app/work/orig_extract/Source/Syndicate.dll'
DEC = '/app/co_decomp/Native-Decompiled/Syndicate.dll.decompiled.c'


def starts():
    src = open(DEC, errors='ignore').read()
    return [int(a, 16) for a in re.findall(r'// Function: FUN_([0-9a-f]+) @', src)]


def body(addr, n=0x30):
    out = subprocess.run(['objdump', '-d', '-M', 'intel', '--no-show-raw-insn',
                          '--start-address=' + hex(addr), '--stop-address=' + hex(addr + n), DLL],
                         capture_output=True, text=True).stdout
    r = []
    for line in out.split('\n'):
        m = re.match(r'\s+([0-9a-f]+):\t(.*)$', line)
        if not m:
            continue
        t = m.group(2).strip()
        if t.startswith('int3') or t.startswith('nop'):
            break
        r.append(t)
        if t.startswith('ret') or 'jmp' in t or t.startswith('call'):
            break
    return r


def classify(addr):
    b = body(addr)
    if b == ['mov    rax,rcx', 'ret']:
        return ('id', 0, b)
    if len(b) == 2 and b[1] == 'ret':
        m = re.match(r'lea    rax,\[rcx\+(0x[0-9a-f]+)\]$', b[0])
        if m:
            return ('off', int(m.group(1), 16), b)
        m = re.match(r'mov    rax,QWORD PTR \[rcx\+(0x[0-9a-f]+)\]$', b[0])
        if m:
            return ('load', int(m.group(1), 16), b)
        m = re.match(r'movabs rax,(0x[0-9a-f]+)$', b[0])
        if m:
            return ('const', int(m.group(1), 16), b)
    if len(b) == 3 and b[2] == 'ret':
        m1 = re.match(r'mov    rax,QWORD PTR \[rcx\+(0x[0-9a-f]+)\]$', b[0])
        m2 = re.match(r'add    rax,(0x[0-9a-f]+)$', b[1])
        if m1 and m2:
            return ('loadadd', (int(m1.group(1), 16), int(m2.group(1), 16)), b)
    return (None, None, b)


def known_text():
    t = ''
    for f in (glob.glob('modules/**/*.cpp', recursive=True) + glob.glob('modules/**/*.h', recursive=True)
              + glob.glob('tests/*.cpp')):
        t += open(f, errors='ignore').read().lower()
    return t


def main():
    lo, hi, name = int(sys.argv[1], 16), int(sys.argv[2], 16), sys.argv[3]
    txt = known_text()
    todo, skipped = [], []
    for a in sorted(x for x in starts() if lo <= x <= hi):
        if hex(a)[2:] in txt:
            continue
        kind, v, b = classify(a)
        if kind is None:
            skipped.append((a, b))
        else:
            todo.append((a, kind, v))
    seen, rep = {}, {}
    for a, kind, v in todo:
        k = (kind, str(v))
        rep[a] = seen.setdefault(k, a)
    out_h = ['// %s.h — generated by tools/gen_leaves.py from the verified objdump classification.' % name,
             '// Every body below is one of the five accepted shapes; anything ambiguous was left out.',
             '#ifndef SYNDICATE_%s_H' % name.upper(),
             '#define SYNDICATE_%s_H' % name.upper(), '', '#include <cstdint>', '', 'namespace tq {', '']
    out_c = ['// %s.cpp — generated by tools/gen_leaves.py' % name,
             '#include "modules/syndicate/src/%s.h"' % name, '', 'namespace tq {', '']
    for a, kind, v in todo:
        fn = 'SynLeaf_%x' % a
        alias = '' if rep[a] == a else '  (same body as SynLeaf_%x)' % rep[a]
        if kind == 'off':
            out_h.append('void* %s(void* p);   // 0x%x  p + 0x%x%s' % (fn, a, v, alias))
        elif kind == 'id':
            out_h.append('void* %s(void* p);   // 0x%x  identity%s' % (fn, a, alias))
        elif kind == 'load':
            out_h.append('void* %s(void* p);   // 0x%x  *(void**)(p + 0x%x)%s' % (fn, a, v, alias))
        elif kind == 'loadadd':
            out_h.append('void* %s(void* p);   // 0x%x  *(void**)(p + 0x%x) + 0x%x%s'
                         % (fn, a, v[0], v[1], alias))
        elif kind == 'const':
            out_h.append('uint64_t %s(void);   // 0x%x  0x%x%s' % (fn, a, v, alias))
        if rep[a] != a:
            continue
        if kind == 'off':
            out_c.append('void* %s(void* p) { return (uint8_t*)p + 0x%x; }   // 0x%x' % (fn, v, a))
        elif kind == 'id':
            out_c.append('void* %s(void* p) { return p; }   // 0x%x' % (fn, a))
        elif kind == 'load':
            out_c.append('void* %s(void* p) { return *(void**)((uint8_t*)p + 0x%x); }   // 0x%x' % (fn, v, a))
        elif kind == 'loadadd':
            out_c.append('void* %s(void* p) { return (uint8_t*)*(void**)((uint8_t*)p + 0x%x) + 0x%x; }   // 0x%x'
                         % (fn, v[0], v[1], a))
        elif kind == 'const':
            out_c.append('uint64_t %s(void) { return 0x%xULL; }   // 0x%x' % (fn, v, a))
    out_h += ['', '}  // namespace tq', '', '#endif  // SYNDICATE_%s_H' % name.upper(), '']
    out_c += ['', '}  // namespace tq', '']
    open('modules/syndicate/src/%s.h' % name, 'w').write('\n'.join(out_h))
    open('modules/syndicate/src/%s.cpp' % name, 'w').write('\n'.join(out_c))
    # the matching test, generated from the same classification
    t = ['// %s_test.cpp — generated by tools/gen_leaves.py' % name,
         '#include "modules/syndicate/src/%s.h"' % name, '',
         '#include <cassert>', '#include <cstdio>', '#include <cstring>', '',
         'using namespace tq;', '', 'static int g_nChecks = 0;',
         '#define CHECK(x) do { ++g_nChecks; assert(x); } while (0)', '', 'int main() {',
         '    static uint8_t aBuf[0x400];', '    std::memset(aBuf, 0, sizeof(aBuf));']
    for a, kind, v in todo:
        fn = 'SynLeaf_%x' % rep[a]
        if kind == 'off':
            t.append('    CHECK(%s(aBuf + 0x100) == (void*)(aBuf + 0x100 + 0x%x));   // 0x%x' % (fn, v, a))
        elif kind == 'id':
            t.append('    CHECK(%s(aBuf + 0x100) == (void*)(aBuf + 0x100));   // 0x%x' % (fn, a))
        elif kind == 'load':
            t.append('    *(void**)(aBuf + 0x100 + 0x%x) = (void*)0x1234; CHECK(%s(aBuf + 0x100) == (void*)0x1234);   // 0x%x' % (v, fn, a))
        elif kind == 'loadadd':
            t.append('    *(void**)(aBuf + 0x100 + 0x%x) = (void*)0x1234; CHECK(%s(aBuf + 0x100) == (void*)(0x1234 + 0x%x));   // 0x%x' % (v[0], fn, v[1], a))
        elif kind == 'const':
            t.append('    CHECK(%s() == 0x%xULL);   // 0x%x' % (fn, v, a))
    t += ['    std::printf("SYNDICATE_%s_OK: %d addresses, %%d checks\\n", g_nChecks);' % (name.upper(), len(todo)),
          '    return 0;', '}', '']
    open('tests/%s_test.cpp' % name, 'w').write('\n'.join(t))
    print('ported %d addresses (%d distinct bodies), skipped %d bodies:' % (len(todo), len(seen), len(skipped)))
    for a, b in skipped:
        print('   skip 0x%x :: %s' % (a, ' | '.join(b)[:100]))


if __name__ == '__main__':
    main()
